import {readFile} from 'node:fs/promises';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const reports=[];
const context=vm.createContext({Float32Array,performance:{timeOrigin:100000},worldSent:false,fr:{idle:321,pipe:0,mod:0,up:1,upBytes:1048576,wait:2,flush:3},pipelinesPending:0,progressChannel:null,BroadcastChannel:class{postMessage(value){reports.push(value)}},texBytesAlive:1024,bufBytesAlive:2048,ubo:{shared:[{}]},bufferPool:new Map([[4294967296+4096,[{},{}]]]),FRAME_SLOTS:3,RING_CHUNK:8388608,texCount:7,contentPipelines:new Map([[1,{}]]),shaderModuleCount:8,bindGroupCache:new Map(),aheadMade:9,aheadUsed:4});
vm.runInContext(await readFile(new URL('../crates/wgr-app/src/gpu_observer.js',import.meta.url),'utf8'),context);
vm.runInContext('wgrRecordFrame(330,1000)',context);
assert.equal(reports.length,0,'loading frames are not gameplay stalls');
context.worldSent=true;
vm.runInContext('wgrRecordFrame(330,2000);wgrReportGpu(6000);wgrReportGpu(6100)',context);
assert.equal(reports.length,2);
assert.equal(reports[0].gpu_frame.epoch_ms,102000);
assert.equal(reports[0].gpu_frame.idle_ms,321);
assert.equal(context.fr.idle,321,'instrumentation must not consume/reset original GPU counters');
assert.equal(reports[1].gpu_memory.uniform_ring_bytes,25165824);
assert.equal(reports[1].gpu_memory.pooled_buffer_bytes,8192);
assert.equal(reports[1].gpu_window.p99_ms,330);
vm.runInContext('for(let i=0;i<2000;i++)wgrRecordFrame(10,7000+i);wgrReportGpu(12000)',context);
assert.equal(reports.at(-1).gpu_window.frames,1024,'frame sample storage is bounded');
assert.equal(reports.at(-1).gpu_window.max_ms,10);
console.log(JSON.stringify({passed:true,gameplay_only:true,epoch_alignment:true,bounded:true,original_counters_preserved:true}));
